def seed(force=False):
    init_db()
    rnd = random.Random(7)
    with Session() as s:
        if s.scalar(select(func.count(AppUser.id))) and not force:
            return False
        users = [("admin", "admin123", "Администратор системы", "admin"),
                 ("head", "head123", "Сагынбаева Гульнара Маратовна", "head"),
                 ("lib", "lib123", "Мухамедова Салтанат Ермековна", "librarian")]
        for login, pwd, name, role in users:
            s.add(AppUser(login=login, password_hash=hash_password(pwd), full_name=name, role=role))
        s.flush()
        lib = s.scalar(select(AppUser).where(AppUser.login == "lib"))
        for i, (t, a, g, p, y, c) in enumerate(BOOKS):
            s.add(Book(isbn=f"978{9965000000 + i * 7919:010d}", title=t, author=a, genre=g, publisher=p, year=y,
                       copies_total=c, copies_available=c))
        today = date.today()
        for i, n in enumerate(NAMES):
            r = Reader(ticket_number=f"{i + 1:06d}", full_name=n, birth_date=date(rnd.randint(1960, 2008), rnd.randint(1, 12), rnd.randint(1, 28)),
                       address=f"г. Астана, {rnd.choice(STREETS)}, {rnd.randint(1, 120)}",
                       phone=f"+7 7{rnd.choice([0, 1, 7])}{rnd.randint(0, 9)} {rnd.randint(100, 999)}-{rnd.randint(10, 99)}-{rnd.randint(10, 99)}",
                       registered_at=today - timedelta(days=rnd.randint(30, 700)))
            s.add(r)
        s.flush()
        readers, books = list(s.scalars(select(Reader))), list(s.scalars(select(Book)))
        readers[-1].is_blocked = True
        # возвращённые выдачи за последние 6 месяцев (для статистики)
        for _ in range(95):
            b, r = rnd.choice(books), rnd.choice(readers)
            issued = today - timedelta(days=rnd.randint(20, 180))
            ret = issued + timedelta(days=rnd.randint(3, 20))
            s.add(Loan(reader_id=r.id, book_id=b.id, user_id=lib.id, issued_at=issued, due_at=issued + timedelta(days=14),
                       returned_at=ret, status="возвращена", renewals=rnd.choice([0, 0, 0, 1])))
        s.flush()
        # активные выдачи, часть просрочена
        used = set()
        for k in range(22):
            b, r = rnd.choice(books), rnd.choice(readers[:-1])
            if (r.id, b.id) in used or b.copies_available <= 0:
                continue
            used.add((r.id, b.id))
            if sum(1 for (rid, _) in used if rid == r.id) > 4:
                continue
            issued = today - timedelta(days=rnd.choice([1, 2, 4, 6, 9, 12, 20, 25, 33, 45]))
            due = issued + timedelta(days=14)
            s.add(Loan(reader_id=r.id, book_id=b.id, user_id=lib.id, issued_at=issued, due_at=due,
                       status="просрочена" if due < today else "выдана"))
            b.copies_available -= 1
        for n, ph, ad in [("Книжный мир", "+7 7172 55-11-22", "г. Астана, ул. Победы, 10"),
                          ("Атамура-Дистрибуция", "+7 727 330-44-55", "г. Алматы, пр. Абая, 143"),
                          ("Эксмо-Казахстан", "+7 727 244-10-10", "г. Алматы, ул. Жарокова, 280")]:
            s.add(Supplier(name=n, phone=ph, address=ad))
        s.flush()
        sup = list(s.scalars(select(Supplier)))
        s.add(PurchaseOrder(supplier_id=sup[0].id, book_id=books[8].id, quantity=5, ordered_at=today - timedelta(days=9), status="отправлен"))
        s.add(PurchaseOrder(supplier_id=sup[1].id, book_id=books[38].id, quantity=3, ordered_at=today - timedelta(days=2), status="создан"))
        s.add(AuditLog(user_id=None, action="Инициализация", description="Созданы демонстрационные данные"))
        s.commit()
        from .services import refresh_overdue
        refresh_overdue(s)
    return True
